// Author: Rasel Al Mamun
// Generates src/scss/base/_tokens.scss from the design tokens (src/design/tokens.json, the
// approved design system's values; the only source of colour, type, spacing and motion).
// Dark is the default theme (:root); light applies under [data-theme="light"].
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = 'src/design/tokens.json';
const target = 'src/scss/base/_tokens.scss';
const tokens = JSON.parse(readFileSync(resolve(root, source), 'utf8'));

const ref = /^\{([\w-]+)\}$/;
const cssValue = (value) => value.replace(ref, 'var(--$1)');
const themed = [...tokens.color.tokens, ...tokens.shadow.tokens];
const flat = [
  ...tokens.spacing.tokens,
  ...tokens.radius.tokens,
  ...tokens.duration.tokens,
  ...tokens.easing.tokens,
  ...tokens.motionscale.tokens,
];

// Resolves {name} references to the referenced token's value in the same theme.
function themeValue(token, theme) {
  const value = token.value[theme];
  const match = value.match(ref);
  if (!match) return value;
  const target = themed.find((t) => t.name === match[1]);
  if (!target) throw new Error(`tokens: "${token.name}" refers to unknown colour {${match[1]}}`);
  return themeValue(target, theme);
}

const lines = [
  '// Author: Rasel Al Mamun',
  `// Generated by tools/tokens.mjs from ${source}. Do not edit; run \`npm run tokens\`.`,
  '',
  '// Sass values (dark theme) for Bootstrap variables that need real values.',
];
for (const token of tokens.color.tokens) {
  lines.push(`$token-${token.name}: ${themeValue(token, 'dark')};`);
}
for (const token of [...tokens.spacing.tokens, ...tokens.radius.tokens]) {
  lines.push(`$token-${token.name}: ${token.value};`);
}
for (const [name, value] of Object.entries(tokens.type.families)) {
  lines.push(`$token-font-${name}: ${value};`);
}
// Fixed sizes only; the fluid clamp() values live in each style's `usage` text
// in tokens.json and are applied by the styles of those components.
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    lines.push(`$token-type-${style.name}-size: ${style.fontSize};`);
    lines.push(`$token-type-${style.name}-line-height: ${style.lineHeight};`);
    lines.push(`$token-type-${style.name}-weight: ${style.fontWeight};`);
  }
}

lines.push('', ':root {');
for (const token of themed) lines.push(`  --${token.name}: ${cssValue(token.value.dark)};`);
for (const token of flat) lines.push(`  --${token.name}: ${token.value};`);
for (const [name, value] of Object.entries(tokens.type.families)) {
  lines.push(`  --font-${name}: ${value};`);
}
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    lines.push(`  --type-${style.name}-size: ${style.fontSize};`);
    lines.push(`  --type-${style.name}-line-height: ${style.lineHeight};`);
    lines.push(`  --type-${style.name}-weight: ${style.fontWeight};`);
    if (style.letterSpacing) {
      lines.push(`  --type-${style.name}-letter-spacing: ${style.letterSpacing};`);
    }
  }
}
lines.push('}', '', '[data-theme="light"] {');
for (const token of themed) lines.push(`  --${token.name}: ${cssValue(token.value.light)};`);
lines.push('}', '');

writeFileSync(resolve(root, target), lines.join('\n'));
console.log(`tokens: wrote ${target}`);
