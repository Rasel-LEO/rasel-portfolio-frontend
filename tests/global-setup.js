// 1.7.4 (F23): the specs read the build from disk (dist/, dist-django/) as well as through the
// preview server, so before any spec runs the builds must match the sources. `npm test` builds
// first (pretest); a direct `npx playwright test` with a stale or missing build rebuilds it here.
// Not used against a running Django site (TEST_TARGET=django), which serves its own files.
import { execSync } from 'node:child_process';
import { existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

// Everything a build is made from. The token partial is generated by every build's prebuild from
// src/design/tokens.json (an input itself), so its own date says nothing.
const INPUTS = ['src', 'public', 'tools', 'vite.config.js', 'package-lock.json'];
const GENERATED = new Set([join('src', 'scss', 'base', '_tokens.scss')]);

function newest(path) {
  if (!existsSync(path) || GENERATED.has(path)) return 0;
  const stat = statSync(path);
  if (!stat.isDirectory()) return stat.mtimeMs;
  let latest = 0;
  for (const entry of readdirSync(path)) latest = Math.max(latest, newest(join(path, entry)));
  return latest;
}

// A build is fresh when its index.html is newer than every input file.
const fresh = (dir) =>
  existsSync(join(dir, 'index.html')) &&
  statSync(join(dir, 'index.html')).mtimeMs >= Math.max(...INPUTS.map(newest));

export default function globalSetup() {
  if (process.env.TEST_TARGET === 'django') return;
  for (const [dir, script] of [
    ['dist', 'build'],
    ['dist-django', 'build:django'],
  ]) {
    if (fresh(dir)) continue;
    console.log(`global-setup: ${dir}/ is missing or older than its sources; npm run ${script}`);
    execSync(`npm run ${script}`, { stdio: 'inherit' });
  }
}
